import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const fonts = [
  ["Regular", "478c558ea716033cd60c03438f628dfa75694dcf6b5f6d505a2f05fd2b4f3823"],
  ["Bold", "1df075a380fc7cb898acf64c1f7b3b4dd780de3caa860178bf929de35817a913"],
];
const check = process.argv.slice(2).join(" ") === "--check";
if (process.argv.length > 2 && !check) throw new Error("Use --check or no arguments.");

function checksum(bytes) {
  let result = 0;
  for (let offset = 0; offset < bytes.length; offset += 4) {
    let word = 0;
    for (let index = 0; index < 4; index++) word = (word << 8) | (bytes[offset + index] ?? 0);
    result = (result + (word >>> 0)) >>> 0;
  }
  return result;
}

function withoutSubstitution(source) {
  const tables = [];
  for (let index = 0; index < source.readUInt16BE(4); index++) {
    const entry = 12 + index * 16,
      tag = source.toString("ascii", entry, entry + 4);
    if (tag === "GSUB") continue;
    const offset = source.readUInt32BE(entry + 8),
      length = source.readUInt32BE(entry + 12);
    if (offset + length > source.length) throw new Error("Invalid source font table.");
    const data = Buffer.from(source.subarray(offset, offset + length));
    if (tag === "head") data.writeUInt32BE(0, 8);
    tables.push({ tag, data });
  }
  if (tables.length !== source.readUInt16BE(4) - 1) throw new Error("Source font lacks GSUB.");
  const count = tables.length,
    directorySize = 12 + count * 16;
  const output = Buffer.alloc(
    directorySize + tables.reduce((size, { data }) => size + ((data.length + 3) & ~3), 0),
  );
  source.copy(output, 0, 0, 4);
  const power = Math.floor(Math.log2(count));
  output.writeUInt16BE(count, 4);
  output.writeUInt16BE(2 ** power * 16, 6);
  output.writeUInt16BE(power, 8);
  output.writeUInt16BE(count * 16 - 2 ** power * 16, 10);
  let offset = directorySize,
    headOffset;
  tables.forEach(({ tag, data }, index) => {
    const entry = 12 + index * 16;
    output.write(tag, entry, 4, "ascii");
    output.writeUInt32BE(checksum(data), entry + 4);
    output.writeUInt32BE(offset, entry + 8);
    output.writeUInt32BE(data.length, entry + 12);
    data.copy(output, offset);
    if (tag === "head") headOffset = offset;
    offset += (data.length + 3) & ~3;
  });
  if (headOffset === undefined) throw new Error("Source font lacks head.");
  output.writeUInt32BE((0xb1b0afba - checksum(output)) >>> 0, headOffset + 8);
  return output;
}

for (const [weight, digest] of fonts) {
  const source = readFileSync(new URL(`../fonts/NotoSans-${weight}.ttf`, import.meta.url));
  if (createHash("sha256").update(source).digest("hex") !== digest)
    throw new Error("Source font does not match pinned provenance.");
  const generated = withoutSubstitution(source);
  const content = `// Generated by scripts/generate-fonts.mjs from the pinned OFL font; do not edit.\n// GSUB is removed; all cmap, glyph and metric tables are retained.\nexport const notoSans${weight} =\n  "data:font/ttf;base64,${generated.toString("base64")}";\n`;
  const target = new URL(`../src/fonts/noto-sans-${weight.toLowerCase()}.ts`, import.meta.url);
  if (check) {
    if (readFileSync(target, "utf8") !== content)
      throw new Error(`Regenerate ${fileURLToPath(target)}.`);
  } else writeFileSync(target, content);
}
