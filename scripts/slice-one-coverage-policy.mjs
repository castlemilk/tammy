import { E2E_IDEMPOTENCY_MODES } from "./e2e-coverage-vocabulary.mjs";

const ALLOWED = "planned_allowed";
const DENIED = "planned_permission_denied";
const NOT_APPLICABLE = "not_applicable_pre_authentication";

const ROLE_NAMES = ["workspace_admin", "business_preparer", "business_lodger", "auditor"];

const OUTCOMES = {
  fresh_challenge: ["fresh_attempt", "terminal_state_after_success", "no_automatic_retry"],
  persistent_command: ["exact_replay", "changed_request_conflict"],
  query: ["not_applicable"],
  recovery_operation: [
    "fresh_invalid_proof_attempt",
    "exact_success_replay",
    "changed_request_conflict",
    "no_automatic_retry",
  ],
  restore: ["external_journal_resume", "exact_replay", "changed_manifest_conflict"],
  session_action: ["state_predicate_election", "terminal_state_after_success"],
  setup_journal: ["exact_replay", "changed_request_conflict"],
};

if (
  Object.keys(OUTCOMES).length !== E2E_IDEMPOTENCY_MODES.length ||
  E2E_IDEMPOTENCY_MODES.some((mode) => !Object.hasOwn(OUTCOMES, mode))
) {
  throw new Error("SLICE_ONE_IDEMPOTENCY_MODES_INCONSISTENT");
}

function roles(...allowedRoles) {
  return Object.fromEntries(
    ROLE_NAMES.map((role) => [role, allowedRoles.includes(role) ? ALLOWED : DENIED]),
  );
}

function preAuthenticationRoles() {
  return Object.fromEntries(ROLE_NAMES.map((role) => [role, NOT_APPLICABLE]));
}

export function coverageProjectionName(name) {
  const snakeCase = name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
  return `${snakeCase}_result`;
}

function rpc({
  failures,
  list = ["not_applicable"],
  mode,
  name,
  preload,
  projection,
  projections,
  rolePolicy,
  route,
  routes,
}) {
  return {
    preload: preload ?? `${name[0].toLowerCase()}${name.slice(1)}`,
    projections: projections ?? [projection ?? coverageProjectionName(name)],
    routes: routes ?? [route],
    roles: rolePolicy,
    principalFailures: failures,
    list: { states: list },
    idempotency: { mode, outcomes: OUTCOMES[mode] },
  };
}

